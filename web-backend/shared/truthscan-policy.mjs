// Application policy over provider label confidence, not binary class scores.
export const TRUTHSCAN_DECISION_RULE = 'truthscan_label_confidence_60_v2';
export const TRUTHSCAN_MINIMUM_CONFIDENCE = 0.6;

export function mapTruthScanClassification(details) {
  const label = details?.final_result;
  const confidence = details?.final_label_confidence;
  if (details?.is_valid === false || typeof label !== 'string' || !label.trim() ||
      label.length > 100 || typeof confidence !== 'number' ||
      !Number.isFinite(confidence) || confidence < 0 || confidence > 100) {
    throw new Error('Invalid TruthScan classification.');
  }
  const score = confidence / 100;
  let verdict = 'uncertain';
  if (score >= TRUTHSCAN_MINIMUM_CONFIDENCE) {
    if (label === 'Real') verdict = 'authentic';
    if (label === 'AI Generated' || label === 'AI Edited') verdict = 'ai_generated';
  }
  const edited = label === 'Digitally Edited';
  const supported = ['Real', 'AI Generated', 'AI Edited'].includes(label);
  const reason = edited ? 'editing_outside_binary_scope'
    : !supported ? 'unsupported_provider_label'
      : score < TRUTHSCAN_MINIMUM_CONFIDENCE ? 'below_label_confidence_threshold' : 'label_confidence_threshold_met';
  const explanation = edited
    ? 'The analysis indicates possible editing. AuthentiScan could not confidently classify the image as Authentic or AI-Generated.'
    : !supported
      ? 'The analysis returned a category outside AuthentiScan’s supported classification. The result is Uncertain.'
      : verdict === 'uncertain'
        ? 'The analysis returned a label confidence below the required 60%. AuthentiScan reports Uncertain.'
        : label === 'AI Edited'
          ? 'The analysis detected possible AI editing with confidence meeting the 60% threshold. AuthentiScan groups AI-edited images under AI-Generated; this does not mean the entire image was generated by AI.'
          : `The analysis classified this image as ${verdict === 'authentic' ? 'Authentic' : 'AI-Generated'} because confidence in the returned label met the 60% threshold.`;
  return {
    provider: 'truthscan', model_version: 'truthscan-generic',
    verdict, decision_rule: TRUTHSCAN_DECISION_RULE,
    minimum_label_confidence: TRUTHSCAN_MINIMUM_CONFIDENCE,
    provider_label: label, provider_label_confidence: score,
    confidence_score: score, confidence_kind: 'provider_label_confidence',
    authentic_score: null, ai_generated_score: null,
    uncertainty_reason: verdict === 'uncertain' ? reason : null,
    readable_explanation: explanation,
  };
}
